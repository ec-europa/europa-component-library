const primitivesRaw = JSON.parse(
  fs.readFileSync(path.join(SOURCE_DIR, 'Primitives.json'), 'utf8'),
);
const lightRaw = JSON.parse(
  fs.readFileSync(path.join(SOURCE_DIR, 'Light.tokens.json'), 'utf8'),
);
const darkRaw = JSON.parse(
  fs.readFileSync(path.join(SOURCE_DIR, 'Dark.tokens.json'), 'utf8'),
);

const primitives = flatten(primitivesRaw);
delete primitives.system; // Figma-only documentation swatch, not a design token
Object.keys(primitives).forEach((key) => {
  if (key.startsWith('system/')) delete primitives[key];
});

const light = flatten(lightRaw);
const dark = flatten(darkRaw);

// -----------------------------------------------------------------------
// 1. Primitives Sass map
// -----------------------------------------------------------------------

function buildPrimitivesScss() {
  const byCategory = {};
  Object.keys(primitives).forEach((key) => {
    const segments = key.split('/');
    const category = segments[0];
    const rest = segments.slice(1);
    const node = primitives[key];
    const scssValue = toScssValue(segments, node.$type, node.$value);
    byCategory[category] = byCategory[category] || {};
    let cursor = byCategory[category];
    rest.forEach((segment, i) => {
      if (i === rest.length - 1) {
        cursor[segment] = scssValue;
      } else {
        cursor[segment] = cursor[segment] || {};
        cursor = cursor[segment];
      }
    });
  });

  let out = GENERATED_BANNER;
  out += '\n// Raw design tokens ("Primitives" in Figma) — the atomic values\n';
  out += '// semantic light/dark tokens alias into. Not mode-dependent.\n\n';
  out += Object.keys(byCategory)
    .sort()
    .map(
      (category) =>
        `$eds-primitive-${category}: ${renderScssMap(byCategory[category])} !default;`,
    )
    .join('\n');
  out += '\n';
  return out;
}

// -----------------------------------------------------------------------
// 2. Semantic maps, split: color (mode-scoped) vs everything else (invariant)
// -----------------------------------------------------------------------

function splitSemantic(flatDict) {
  const color = {};
  const rest = {};
  Object.keys(flatDict).forEach((key) => {
    const node = flatDict[key];
    if (node.$type === 'color') {
      color[key] = node;
    } else {
      rest[key] = node;
    }
  });
  return { color, rest };
}

const lightSplit = splitSemantic(light);
const darkSplit = splitSemantic(dark);

function buildColorScssMap(colorDict) {
  const nested = {};
  Object.keys(colorDict).forEach((key) => {
    const segments = key.split('/');
    const node = colorDict[key];
    const scssValue = toScssValue(segments, node.$type, node.$value);
    let cursor = nested;
    segments.forEach((segment, i) => {
      if (i === segments.length - 1) {
        cursor[segment] = scssValue;
      } else {
        cursor[segment] = cursor[segment] || {};
        cursor = cursor[segment];
      }
    });
  });
  return nested;
}

// Composite `box-shadow`-ready value per elevation level, built from the
// (mode-scoped) shadow color + the (mode-invariant) offset/blur/spread.
function buildShadowComposites(colorDict, restDict) {
  const levels = new Set();
  Object.keys(colorDict).forEach((key) => {
    const match = key.match(/^shadow\/elevation\/(level-\d+)\/color$/);
    if (match) levels.add(match[1]);
  });
  const composites = {};
  levels.forEach((level) => {
    const x = toScssValue(
      ['shadow'],
      'number',
      restDict[`shadow/elevation/${level}/x`].$value,
    );
    const y = toScssValue(
      ['shadow'],
      'number',
      restDict[`shadow/elevation/${level}/y`].$value,
    );
    const blur = toScssValue(
      ['shadow'],
      'number',
      restDict[`shadow/elevation/${level}/blur`].$value,
    );
    const spread = toScssValue(
      ['shadow'],
      'number',
      restDict[`shadow/elevation/${level}/spread`].$value,
    );
    const color = toScssValue(
      ['shadow'],
      'color',
      colorDict[`shadow/elevation/${level}/color`].$value,
    );
    composites[level] = `${x} ${y} ${blur} ${spread} ${color}`;
  });
  return composites;
}

function buildColorMapsScss() {
  const lightNested = buildColorScssMap(lightSplit.color);
  const darkNested = buildColorScssMap(darkSplit.color);
  const lightShadowComposite = buildShadowComposites(
    lightSplit.color,
    lightSplit.rest,
  );
  const darkShadowComposite = buildShadowComposites(
    darkSplit.color,
    darkSplit.rest,
  );
  lightNested.shadow = lightNested.shadow || {};
  lightNested.shadow.composite = lightShadowComposite;
  darkNested.shadow = darkNested.shadow || {};
  darkNested.shadow.composite = darkShadowComposite;

  let out = GENERATED_BANNER;
  out +=
    '\n// Semantic color tokens (mode-dependent). shadow.composite.level-N\n';
  out += '// is a ready-to-use `box-shadow` value combining the mode-scoped\n';
  out += '// shadow color with the mode-invariant offset/blur/spread.\n\n';
  out += `$eds-color-light: ${renderScssMap(lightNested)} !default;\n`;
  out += `$eds-color-dark: ${renderScssMap(darkNested)} !default;\n`;
  return out;
}

function buildInvariantScss(prefix, restDict, categories, banner) {
  const nested = {};
  Object.keys(restDict).forEach((key) => {
    const segments = key.split('/');
    if (!categories.includes(segments[0])) return;
    const node = restDict[key];
    const scssValue = toScssValue(segments, node.$type, node.$value);
    let cursor = nested;
    segments.forEach((segment, i) => {
      if (i === segments.length - 1) {
        cursor[segment] = scssValue;
      } else {
        cursor[segment] = cursor[segment] || {};
        cursor = cursor[segment];
      }
    });
  });

  let out = GENERATED_BANNER;
  out += `\n${banner}\n\n`;
  out += categories
    .filter((category) => nested[category])
    .map(
      (category) =>
        `$eds-${category}: ${renderScssMap(nested[category])} !default;`,
    )
    .join('\n');
  out += '\n';
  return out;
}

// -----------------------------------------------------------------------
// 3. _custom-properties.scss
// -----------------------------------------------------------------------

function buildCustomPropertyLines() {
  const restLines = [];
  const seenRestKeys = new Set();
  Object.keys(lightSplit.rest)
    .sort()
    .forEach((key) => {
      if (seenRestKeys.has(key)) return;
      seenRestKeys.add(key);
      const segments = key.split('/');
      const node = lightSplit.rest[key];
      const scssValue = toScssValue(segments, node.$type, node.$value);
      restLines.push(`  ${cssVarName('eds', segments)}: ${scssValue};`);
    });

  function colorLines(colorDict, restDict) {
    const lines = [];
    Object.keys(colorDict)
      .sort()
      .forEach((key) => {
        const segments = key.split('/');
        const node = colorDict[key];
        const scssValue = toScssValue(segments, node.$type, node.$value);
        lines.push(`  ${cssVarName('eds', segments)}: ${scssValue};`);
      });
    const composites = buildShadowComposites(colorDict, restDict);
    Object.keys(composites)
      .sort()
      .forEach((level) => {
        lines.push(
          `  ${cssVarName('eds', ['shadow', 'elevation', level])}: ${composites[level]};`,
        );
      });
    return lines;
  }

  return {
    restLines,
    lightColorLines: colorLines(lightSplit.color, lightSplit.rest),
    darkColorLines: colorLines(darkSplit.color, darkSplit.rest),
  };
}

function buildCustomPropertiesScss() {
  const { restLines, lightColorLines, darkColorLines } =
    buildCustomPropertyLines();

  let out = GENERATED_BANNER;
  out += '\n:root {\n';
  out += '  // Mode-invariant tokens (spacing, sizing, font, border-radius,\n';
  out += '  // border-width, opacity, shadow offset/blur/spread)\n';
  out += `${restLines.join('\n')}\n\n`;
  out += '  // Semantic color tokens — light mode (default)\n';
  out += `${lightColorLines.join('\n')}\n`;
  out += '}\n\n';
  out += '[data-theme="dark"] {\n';
  out += '  // Semantic color tokens — dark mode\n';
  out += `${darkColorLines.join('\n')}\n`;
  out += '}\n';
  return out;
}

// Same custom properties, but as plain, dependency-free CSS (`/* */`
// comments instead of Sass' `//`) for the standalone showcase page to
// <link> directly — no Sass build step needed to view it.
function buildTokensCss() {
  const { restLines, lightColorLines, darkColorLines } =
    buildCustomPropertyLines();

  let out =
    '/* Generated by `scripts/generate-tokens.js`. Do not edit by hand. */\n';
  out += '\n:root {\n';
  out += `${restLines.join('\n')}\n`;
  out += `${lightColorLines.join('\n')}\n`;
  out += '}\n\n';
  out += '[data-theme="dark"] {\n';
  out += `${darkColorLines.join('\n')}\n`;
  out += '}\n';
  return out;
}

// -----------------------------------------------------------------------
// 4. tokens/tokens.json (flat reference export)
// -----------------------------------------------------------------------

function buildTokensJson() {
  const out = { primitives: {}, light: {}, dark: {} };
  Object.keys(primitives).forEach((key) => {
    const node = primitives[key];
    out.primitives[key] = { type: node.$type, value: node.$value };
  });
  [
    ['light', light],
    ['dark', dark],
  ].forEach(([modeName, dict]) => {
    Object.keys(dict).forEach((key) => {
      const node = dict[key];
      const alias = node.$extensions && node.$extensions['com.figma.aliasData'];
      out[modeName][key] = {
        type: node.$type,
        value: node.$value,
        ...(alias ? { aliasOf: alias.targetVariableName } : {}),
      };
    });
  });
  return out;
}

