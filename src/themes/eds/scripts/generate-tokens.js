#!/usr/bin/env node
/**
 * ECL EDS theme: token generator.
 *
 * Reads the raw Figma "W3C Design Tokens" JSON exports committed under
 * `tokens/source/` (Primitives.json, Light.tokens.json, Dark.tokens.json) and
 * generates:
 *   - maps/primitives.scss    ($eds-primitive-* Sass maps, one per top-level
 *                              primitive category)
 *   - maps/color.scss         ($eds-color-light / $eds-color-dark semantic
 *                              color maps, incl. a composite shadow value per
 *                              elevation level)
 *   - maps/spacing.scss       ($eds-spacing, $eds-sizing)
 *   - maps/typography.scss    ($eds-font-family, $eds-font-size, etc.)
 *   - maps/shape.scss         ($eds-border-radius, $eds-border-width)
 *   - maps/opacity.scss       ($eds-opacity)
 *   - _custom-properties.scss (:root + [data-theme="dark"] CSS custom
 *                              properties, generated from the semantic maps)
 *   - tokens/tokens.json       (flat, resolved reference export: every
 *                              primitive + semantic token, its value, type,
 *                              and — for semantic tokens — the primitive it
 *                              aliases)
 *
 * This is codegen: re-run this script after replacing the source JSON files,
 * review the diff, and commit the regenerated output alongside it.
 *
 * Usage: node scripts/generate-tokens.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'tokens/source');
const MAPS_DIR = path.join(ROOT, 'maps');
const SHOWCASE_DIR = path.join(ROOT, 'showcase');

const GENERATED_BANNER = `// This file is generated by \`scripts/generate-tokens.js\` from the JSON
// files in \`tokens/source/\`. Do not edit by hand — re-run the script and
// commit the diff instead.\n`;

// -----------------------------------------------------------------------
// JSON flattening
// -----------------------------------------------------------------------

/**
 * Walks a W3C Design Tokens tree and returns a flat map of
 * 'path/joined/with/slashes' -> the token node ({ $type, $value, $extensions }).
 */
function flatten(node, prefix = '', out = {}) {
  if (node && typeof node === 'object') {
    if (Object.prototype.hasOwnProperty.call(node, '$value')) {
      out[prefix] = node;
      return out;
    }
    Object.keys(node).forEach((key) => {
      if (key.startsWith('$')) return;
      flatten(node[key], prefix ? `${prefix}/${key}` : key, out);
    });
  }
  return out;
}

// -----------------------------------------------------------------------
// Value conversion
// -----------------------------------------------------------------------

function pxToRem(px) {
  const rem = px / 16;
  // Trim floating point noise (e.g. 0.1 + 0.2), keep up to 4 decimals.
  return `${parseFloat(rem.toFixed(4))}rem`;
}

function percentStringToEm(value) {
  // Figma exports letter-spacing / paragraph-spacing as a percentage of the
  // font size ("2%", "150%", "0"). That is exactly what CSS `em` means
  // relative to the current font-size, so "2%" -> "0.02em".
  if (typeof value !== 'string') return value;
  const match = value.trim().match(/^(-?\d+(?:\.\d+)?)%$/);
  if (!match) return value === '0' ? '0' : value;
  const fraction = parseFloat(match[1]) / 100;
  return fraction === 0 ? '0' : `${parseFloat(fraction.toFixed(4))}em`;
}

// Shortens a #RRGGBB[AA] hex string to #RGB[A] when every channel pair
// repeats its digit (stylelint's color-hex-length rule requires this).
function shortenHex(hex) {
  const pairs = hex.slice(1).match(/.{2}/g);
  const canShorten = pairs.every((pair) => pair[0] === pair[1]);
  if (!canShorten) return hex;
  return `#${pairs.map((pair) => pair[0]).join('')}`;
}

function colorToHex(value) {
  const alphaHex =
    value.alpha === 1
      ? ''
      : Math.round(value.alpha * 255)
          .toString(16)
          .padStart(2, '0')
          .toUpperCase();
  return shortenHex(`${value.hex}${alphaHex}`);
}

/** Renders a token's $value as a Sass literal, per its $type / path. */
function toScssValue(pathSegments, type, value) {
  const category = pathSegments[0];

  if (type === 'color') return colorToHex(value);

  if (type === 'string') {
    if (
      category === 'font' &&
      (pathSegments[1] === 'letter-spacing' ||
        pathSegments[1] === 'paragraph-spacing')
    ) {
      return percentStringToEm(value);
    }
    // text-decoration values ("none", "Underline", "Uppercase") are CSS
    // keywords - lowercase them and pass through unquoted.
    if (category === 'font' && pathSegments[1] === 'text-decoration') {
      return value.toLowerCase();
    }
    // The source only names the typeface itself ("Inter") with no fallback
    // stack, so a browser that hasn't loaded it falls back to whatever
    // default the UA picks (often a serif) instead of a plain sans-serif.
    // Append a generic fallback, matching ec's own $font-family convention.
    if (category === 'font' && pathSegments[1] === 'family') {
      return `'${value}', arial, sans-serif`;
    }
    return `'${value}'`;
  }

  if (type === 'number') {
    if (category === 'opacity') return `${value / 100}`;
    if (category === 'border-radius' || category === 'border-width') {
      return `${value}px`;
    }
    if (category === 'shadow') return `${value}px`; // offset/blur/spread
    if (category === 'font' && pathSegments[1] === 'paragraph-spacing') {
      return `${value}`; // 0 (the '150%' case is a string, handled above)
    }
    if (category === 'font' && pathSegments[1] === 'weight') return `${value}`;
    // dimension, sizing, spacing, font/size, font/line-height -> rem
    return pxToRem(value);
  }

  throw new Error(
    `Unhandled token type "${type}" at ${pathSegments.join('/')}`,
  );
}

// -----------------------------------------------------------------------
// Sass map rendering
// -----------------------------------------------------------------------

/** Renders a nested object as a Sass map literal (2-space indent per level). */
function renderScssMap(node, indent = 0) {
  const pad = '  '.repeat(indent);
  const innerPad = '  '.repeat(indent + 1);
  const isLeaf = typeof node !== 'object';
  if (isLeaf) {
    // A leaf value with a top-level comma (e.g. a 'Inter', arial,
    // sans-serif font stack) would otherwise be misread as multiple map
    // entries by the Sass parser - wrap it as a single list value instead.
    if (typeof node === 'string' && node.includes(',')) return `(${node})`;
    return node;
  }

  const entries = Object.keys(node).map((key) => {
    const quotedKey = `'${key}'`;
    return `${innerPad}${quotedKey}: ${renderScssMap(node[key], indent + 1)}`;
  });
  return `(\n${entries.join(',\n')},\n${pad})`;
}

// 1-2 char abbreviations for the top-level token category, applied only to
// generated CSS custom property names (kept full-length in Sass map
// variable names) - shrinks the compiled CSS meaningfully given how many
// custom properties this theme emits. Mirrors ec's own shorthand aliases
// (--c-p, --fs-m, --s-m, --sh-1, ...).
const CATEGORY_ABBREVIATIONS = {
  color: 'c',
  spacing: 'sp',
  sizing: 'sz',
  font: 'f',
  'border-radius': 'br',
  'border-width': 'bw',
  opacity: 'op',
  shadow: 'sh',
};

function cssVarName(prefix, pathSegments) {
  const [category, ...rest] = pathSegments;
  const abbreviatedCategory = CATEGORY_ABBREVIATIONS[category] || category;
  const abbreviatedSegments = [abbreviatedCategory, ...rest];
  // Source segments like 'default--hover' use a double dash as an internal
  // state separator; collapse to single dashes so the result is valid
  // kebab-case (stylelint's custom-property-pattern rejects '--' mid-name).
  return `--${prefix}-${abbreviatedSegments.join('-')}`.replace(
    /-{2,}/g,
    (m, offset) => (offset === 0 ? m : '-'),
  );
}

