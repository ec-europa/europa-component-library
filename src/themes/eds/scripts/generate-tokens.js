async function main() {
  fs.mkdirSync(MAPS_DIR, { recursive: true });

  fs.writeFileSync(
    path.join(MAPS_DIR, 'primitives.scss'),
    buildPrimitivesScss(),
  );
  fs.writeFileSync(path.join(MAPS_DIR, 'color.scss'), buildColorMapsScss());
  fs.writeFileSync(
    path.join(MAPS_DIR, 'spacing.scss'),
    buildInvariantScss(
      'eds',
      lightSplit.rest,
      ['spacing', 'sizing'],
      '// Mode-invariant spacing / sizing scale.',
    ),
  );
  fs.writeFileSync(
    path.join(MAPS_DIR, 'typography.scss'),
    buildInvariantScss(
      'eds',
      lightSplit.rest,
      ['font'],
      '// Mode-invariant typography scale.',
    ),
  );
  fs.writeFileSync(
    path.join(MAPS_DIR, 'shape.scss'),
    buildInvariantScss(
      'eds',
      lightSplit.rest,
      ['border-radius', 'border-width'],
      '// Mode-invariant border-radius / border-width scale.',
    ),
  );
  fs.writeFileSync(
    path.join(MAPS_DIR, 'opacity.scss'),
    buildInvariantScss(
      'eds',
      lightSplit.rest,
      ['opacity'],
      '// Mode-invariant opacity scale.',
    ),
  );
  fs.writeFileSync(
    path.join(ROOT, '_custom-properties.scss'),
    buildCustomPropertiesScss(),
  );
  fs.writeFileSync(
    path.join(ROOT, 'tokens/tokens.json'),
    `${JSON.stringify(buildTokensJson(), null, 2)}\n`,
  );

  fs.mkdirSync(SHOWCASE_DIR, { recursive: true });
  fs.writeFileSync(path.join(SHOWCASE_DIR, 'tokens.css'), buildTokensCss());
  fs.writeFileSync(path.join(SHOWCASE_DIR, 'index.html'), buildShowcaseHtml());

  // Re-format everything this script just wrote with the repo's Prettier
  // config, so generated output always matches `pnpm pretty-check`.
  const generatedFiles = [
    path.join(MAPS_DIR, 'primitives.scss'),
    path.join(MAPS_DIR, 'color.scss'),
    path.join(MAPS_DIR, 'spacing.scss'),
    path.join(MAPS_DIR, 'typography.scss'),
    path.join(MAPS_DIR, 'shape.scss'),
    path.join(MAPS_DIR, 'opacity.scss'),
    path.join(ROOT, '_custom-properties.scss'),
    path.join(ROOT, 'tokens/tokens.json'),
    path.join(SHOWCASE_DIR, 'tokens.css'),
    path.join(SHOWCASE_DIR, 'index.html'),
  ];
  const prettier = require(
    require.resolve('prettier', { paths: [ROOT, path.join(ROOT, '../../..')] }),
  );
  await Promise.all(
    generatedFiles.map(async (file) => {
      const source = fs.readFileSync(file, 'utf8');
      const config = (await prettier.resolveConfig(file)) || {};
      const formatted = await prettier.format(source, {
        ...config,
        filepath: file,
      });
      fs.writeFileSync(file, formatted);
    }),
  );
  console.log('Generated eds theme tokens:');

  console.log(`  - ${Object.keys(primitives).length} primitives`);

  console.log(
    `  - ${Object.keys(light).length} semantic tokens per mode (light/dark)`,
  );
}

main();
